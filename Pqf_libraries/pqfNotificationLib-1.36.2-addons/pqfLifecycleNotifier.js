// ----------------------------------------------------------------------
// Notification rules for lifecycle changes
// ----------------------------------------------------------------------
//
// Notification rules are specified as an array of JSON objects, each of which defines one rule.
//
// Each rule has the following components. Note that you can specify several rules for the same state in consideration.
//
// stateId: string | true. The ID of the lifecycle state in consideration. Can be true, meaning 'any state'.
// whenCommented: {
//		notifyStaticEmails: array of strings | null
//		notifyRelationTypes: array of string | null 
//		notifyUserRoles: array of strings | null
//		useEmailTemplate: function which generates subject and body of emails, see section 'Mail template functions' below for details and examples.
// }
// whenEnteringFromStateIds: Array of {
//		stateId: string | true. The ID of the lifecycle state the state in consideration was entered from (previous state). Can be true, meaning 'any state'.
//		notificationType: string. The type of notification. IMPORTANT: This string will be part of the ID that identifies the message if it goes to the outbox. Messages in the outbox can be updated or removed by their ID.
//		notifyStaticEmails: array of strings (email addresses) | null
//		notifyRelationTypes: array of string (IDs of relation types) | null 
//		notifyUserRoles: array of strings (IDs of user roles) | null
//		useEmailTemplate: function which returns {"subject": string, "body": string}, see section 'Mail template functions' below for examples
//		outboxOptions: { // If not present or null, the mails generated by this rule will be sent immediately
//			sendAtDays: null | array of non-negative integers.
//								Default is null.
//								If it contains 0 it means 'send immediately'.
//								Send that many days after the message has been put into the outbox.
//								**If this option is used, make sure that the outbox is processed daily**, see OUTBOX_PROCESSING_SCHEDULE.
//								USE THIS OPTION AS ALTERNATIVE TO 'repeatTimes'. If both options are set, 'sendAtDays' has preference.
//			repeatTimes: null | non-negative integer.
//								Default is 0.
//								Repeat sending the message with each outbox processing.
//								Note: Immediate send-out is NOT included in this number!
//								USE THIS OPTION AS ALTERNATIVE TO 'sendAtDays'. If both options are set, 'sendAtDays' has preference.
//			notBeforeDays: null | non-negative integer.
//								Default is 0.
//								0 or null means 'send immediately'.
//								Otherwise it combines with 'repeatTimes' and sends the first message not before that many days after today.
//			[same outboxOptions as below can also be used here: removeInfoItems - but they might not make that much sense here]
//		}
// }
// whenExitedToStateIds: Array of {
//		stateId: string | true. The ID of the lifecycle state the state in consideration was exited to (next state). Can be true, meaning 'any state'.
//		notificationType: string. The type of notification
//		notifyStaticEmails: array of strings (email addresses) | null
//		notifyRelationTypes: array of string (IDs of relation types) | null 
//		notifyUserRoles: array of strings (IDs of user roles) | null
//		useEmailTemplate: function which returns {"subject": string, "body": string}, see section 'Mail template functions' below for examples
//		useEmailTemplateForRequester: dito. This is to notify the user that has entered the state in consideration.
//		outboxOptions: { // If not present or null, the mails generated by this rule will be sent immediately
//			removeInfoItems: boolean.
//								Default is false.
//								Remove all info items from all envelopes matching the rule ID (stateId) and object ID.
//								Note: This option should NOT be used together with the above options in 'outboxOptions',
//								i.e., in one state transition rule we either put OR remove info items from the outbox.
//			[same outboxOptions as above can also be used here: sendAtDays, repeatTimes, notBeforeDays - but they might not make that much sense here]
//		}
// }
//

