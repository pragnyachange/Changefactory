// Example 1: Notification for when a comment has been made
// --------------------------------------------------------

function createProjectCommentMail(receiverInfos, actorInfos, projectInfos, language, outputType) {
    let reason = "";
    let subject = "";	
    let body = "";
	switch(outputType) {
	case "infoItem":
		let html = "<p>";
		html += "Im Projekt <a href=\"" + projectInfos.url + "\"><b>" + projectInfos.name + "</b></a> wurde vom Benutzer <b>" + actorInfos.name + "</b> folgender Kommentar erfasst:" + "<br>";
		html += "<i>" + (projectInfos.comment ? projectInfos.comment : "[kein Kommentar erfasst]") + "</i>";
		if(receiverInfos.roleName) {
			reason = "Du erhältst diese Benachrichtigung, weil du die Benutzerrolle " + receiverInfos.roleName + " hast.";
		}
		if(receiverInfos.relationName) {
			reason = "Du erhältst diese Benachrichtigung, weil du zum Projekt die Beziehung " + receiverInfos.relationName + " hast.";
		}
		html += reason + "</p>";
		return html;
	case "envelope":
		switch(language) {
			case "en":
				subject = (projectInfos ? "New comment in project " + projectInfos.name : "New comments");
				break;
			default:
				subject = (projectInfos ? "Neuer Kommentar im Projekt " + projectInfos.name : "Neue Kommentare");
		}
        body = "<p>" + (receiverInfos.resourceName ? "Hallo " + receiverInfos.resourceName + "!" : (receiverInfos.name ? "Hallo " + receiverInfos.name + "!" : "Hallo!")) + "</p>";
		body += pqfNotificationLib.infoItemsPlaceholderText;
		body += "<p>Diese Nachricht ist rein informativ. Es sind keine Aktionen von dir gefordert. Bitte antworte auch nicht auf diese E-Mail.</p>";
		body += "<p>Dein PQFORCE Notifikationssystem</p>";
		return {
			"subject": subject,
			"body": body
		};
	default: // includes "email":
		switch(language) {
			case "en":
				subject = (projectInfos ? "New comment in project " + projectInfos.name : "New comments");
				break;
			default:
				subject = (projectInfos ? "Neuer Kommentar im Projekt " + projectInfos.name : "Neue Kommentare");
		}
		body = "<p>" + (receiverInfos.resourceName ? "Hallo " + receiverInfos.resourceName + "!" : (receiverInfos.name ? "Hallo " + receiverInfos.name + "!" : "Hallo!")) + "</p>";
		if(receiverInfos.roleName) {
			reason = "<p>Du erhältst diese Benachrichtigung, weil du die Benutzerrolle " + receiverInfos.roleName + " hast.</p>";
		}
		if(receiverInfos.relationName) {
			reason = "<p>Du erhältst diese Benachrichtigung, weil du zum Projekt die Beziehung " + receiverInfos.relationName + " hast.</p>";
		}
		body += reason;
		body += "<p>Diese Nachricht ist rein informativ. Es sind keine Aktionen von dir gefordert. Bitte antworte auch nicht auf diese E-Mail.</p>";
		body += "<p>Dein PQFORCE Notifikationssystem</p>";
		return {
			"subject": subject,
			"body": body
		};
	}
}

// Example 2: Notification for when a decision request has been made
// -----------------------------------------------------------------

function createProjectDecisionRequestMail(receiverInfos, actorInfos, projectInfos, language, outputType) {
	switch(outputType) {
	case "infoItem":
		return "";
		break;
	default:
		let subject = "Entscheidungsanfrage im Projekt " + projectInfos.name;
		let body = "<p>" + (receiverInfos.resourceName ? "Hallo " + receiverInfos.resourceName + "!" : (receiverInfos.name ? "Hallo " + receiverInfos.name + "!" : "Hallo!")) + "</p>";
		body += "<p>Das Projekt " + projectInfos.name + " wurde vom Benutzer " + actorInfos.name + " in den Zustand " + projectInfos.stateNow.name + " gesetzt. Davor war es im Zustand " + projectInfos.stateBefore.name + ". Folgender Kommenter wurde dabei erfasst:</p>";
		body += "<p>" + (projectInfos.comment ? projectInfos.comment : "[kein Kommentar erfasst]") + "</p>";
		let reason = "";
		if(receiverInfos.roleName) {
			reason += "<p>Du erhältst diese Benachrichtigung, weil du die Benutzerrolle " + receiverInfos.roleName + " hast. Du bist damit berechtigt, eine Entscheidung zu treffen.</p>";
		}
		if(receiverInfos.relationName) {
			reason += "<p>Du erhältst diese Benachrichtigung, weil du zum Projekt die Beziehung " + receiverInfos.relationName + " hast. Du bist damit berechtigt, eine Entscheidung zu treffen.</p>";
		}
		if(reason) {
			body += reason;
		}
		if(receiverInfos.requestText) {
			body += "<p>" + receiverInfos.requestText + "</p>";
		}
		body += "<p>Mit diesem <a href=\"" + projectInfos.url + "\">Link</a> gelangst du direkt zum Projekt auf die Ansicht \"Details\", wo du den Lebenszyklus-Zustand verändern kannst. Bitte antworte nicht auf diese E-Mail.</p>";
		body += "<p>Dein PQFORCE Notifikationssystem</p>";
		return {
			"subject": subject,
			"body": body
		};
	}
}

